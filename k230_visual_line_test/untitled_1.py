# ============================================================
# K230 颜色巡线
#
# 功能：
# 1. 摄像头采集图像
# 2. 根据 LAB 阈值寻找指定颜色赛道
# 3. 找到最大的色块
# 4. 获取 x / y / w / h
# 5. 通过 UART 发送给单片机
#
# 适用于 Yahboom K230 + CanMV 固件
# ============================================================

import time
import os
import gc

from media.sensor import *
from media.display import *
from media.media import *

# 亚博串口和通信协议
from ybUtils.YbUart import YbUart
from libs.YbProtocol import YbProtocol


# ============================================================
# 1. 基本参数
# ============================================================

WIDTH = 640
HEIGHT = 480

# ------------------------------------------------------------
# 要巡的颜色
#
# 可填写：
# "red"
# "green"
# "blue"
# "black"
# ------------------------------------------------------------

TARGET_COLOR = "black"


# ============================================================
# 2. LAB 颜色阈值
#
# 格式：
# (L_min, L_max, A_min, A_max, B_min, B_max)
#
# 注意：
# 不同比赛场地、灯光、摄像头角度下必须重新调整。
# ============================================================

COLOR_THRESHOLDS = {

    # 红色
    "red": (
        0, 66,
        7, 127,
        3, 127
    ),

    # 绿色
    "green": (
        42, 100,
        -128, -17,
        6, 66
    ),

    # 蓝色
    "blue": (
        43, 99,
        -43, -4,
        -56, -7
    ),

    # 黑色
    #
    # 这是一个通用起始值。
    # 如果比赛地图黑线识别不稳定，需要现场调整。
    "black": (
        0, 35,
        -128, 127,
        -128, 127
    )
}


# ============================================================
# 3. 色块过滤参数
# ============================================================

# 最小像素数量
PIXELS_THRESHOLD = 100

# 最小色块面积
AREA_THRESHOLD = 500


# ============================================================
# 4. 初始化串口
# ============================================================

# K230 与单片机通信
# 波特率必须和单片机一致

uart = YbUart(
    baudrate=115200
)

# 亚博通信协议
pto = YbProtocol()


# ============================================================
# 5. 初始化摄像头
# ============================================================

sensor = None


def init_camera():

    global sensor

    sensor = Sensor()

    # 重置摄像头
    sensor.reset()

    # 640 × 480
    sensor.set_framesize(
        width=WIDTH,
        height=HEIGHT
    )

    # 颜色识别使用 RGB565
    sensor.set_pixformat(
        Sensor.RGB565
    )

    print("Camera init OK")


# ============================================================
# 6. 初始化显示
# ============================================================

def init_display():

    # K230 屏幕显示，同时允许 IDE 查看
    Display.init(
        Display.ST7701,
        to_ide=True
    )

    # 初始化媒体系统
    MediaManager.init()

    print("Display init OK")


# ============================================================
# 7. 找最大色块
# ============================================================

def get_largest_blob(blobs):

    if not blobs:
        return None

    largest = None
    largest_area = 0

    for blob in blobs:

        # blob:
        #
        # blob[0] = x
        # blob[1] = y
        # blob[2] = w
        # blob[3] = h
        # blob[4] = pixels
        # blob[5] = cx
        # blob[6] = cy

        w = blob[2]
        h = blob[3]

        area = w * h

        if area > largest_area:

            largest_area = area
            largest = blob

    return largest


# ============================================================
# 8. 向单片机发送巡线数据
# ============================================================

def send_line_data(x, y, w, h):

    # 使用亚博协议封装颜色识别数据
    #
    # 功能号为 01
    #
    # 最终数据中包含：
    # x
    # y
    # w
    # h

    data = pto.get_color_data(
        x,
        y,
        w,
        h
    )

    uart.send(data)

    print(
        "UART:",
        data
    )


# ============================================================
# 9. 处理一帧图像
# ============================================================

def process_image(img):

    threshold = COLOR_THRESHOLDS[
        TARGET_COLOR
    ]

    # --------------------------------------------------------
    # 查找指定颜色
    # --------------------------------------------------------

    blobs = img.find_blobs(

        [threshold],

        pixels_threshold=PIXELS_THRESHOLD,

        area_threshold=AREA_THRESHOLD,

        merge=True
    )

    # 没找到线
    if not blobs:

        return False

    # --------------------------------------------------------
    # 找最大的色块
    # --------------------------------------------------------

    blob = get_largest_blob(blobs)

    if blob is None:

        return False


    # --------------------------------------------------------
    # 获取色块信息
    # --------------------------------------------------------

    x = blob[0]
    y = blob[1]

    w = blob[2]
    h = blob[3]

    cx = blob[5]
    cy = blob[6]


    # --------------------------------------------------------
    # 在屏幕画出识别结果
    # --------------------------------------------------------

    img.draw_rectangle(

        (x, y, w, h),

        color=(255, 0, 0),

        thickness=3
    )

    img.draw_cross(

        cx,
        cy,

        color=(0, 255, 0),

        thickness=3
    )


    # --------------------------------------------------------
    # 画出摄像头中心线
    # --------------------------------------------------------

    img.draw_line(

        WIDTH // 2,
        0,

        WIDTH // 2,
        HEIGHT,

        color=(0, 0, 255),

        thickness=2
    )


    # --------------------------------------------------------
    # 计算当前巡线误差，仅用于调试
    # --------------------------------------------------------

    error = cx - WIDTH // 2


    # --------------------------------------------------------
    # 显示信息
    # --------------------------------------------------------

    img.draw_string_advanced(

        10,
        10,

        25,

        "color: " + TARGET_COLOR,

        color=(255, 255, 255)
    )

    img.draw_string_advanced(

        10,
        40,

        25,

        "cx: " + str(cx),

        color=(255, 255, 255)
    )

    img.draw_string_advanced(

        10,
        70,

        25,

        "err: " + str(error),

        color=(255, 255, 255)
    )


    # --------------------------------------------------------
    # 把 x y w h 发给单片机
    # --------------------------------------------------------

    send_line_data(

        x,
        y,
        w,
        h
    )


    print(
        "x =", x,
        "y =", y,
        "w =", w,
        "h =", h,
        "cx =", cx,
        "error =", error
    )

    return True


# ============================================================
# 10. 主程序
# ============================================================

def main():

    print("==============================")
    print("K230 Color Line Tracking")
    print("Target:", TARGET_COLOR)
    print("==============================")


    try:

        # 初始化摄像头
        init_camera()

        # 初始化显示
        init_display()

        # 启动摄像头
        sensor.run()

        # 等摄像头稳定
        time.sleep_ms(1000)


        # ----------------------------------------------------
        # 主循环
        # ----------------------------------------------------

        while True:

            # 防止系统完全占满
            time.sleep_ms(10)

            # 获取一帧
            img = sensor.snapshot()

            # 颜色巡线
            process_image(img)

            # 显示画面
            Display.show_image(img)

            # 回收内存
            gc.collect()


    except KeyboardInterrupt:

        print("Program stopped")


    except BaseException as e:

        print(
            "Error:",
            e
        )


    finally:

        # ----------------------------------------------------
        # 释放资源
        # ----------------------------------------------------

        if isinstance(sensor, Sensor):

            sensor.stop()

        Display.deinit()

        MediaManager.deinit()

        print("Exit")


# ============================================================
# 11. 启动
# ============================================================

main()
