import time
import gc

from media.sensor import *
from media.display import *
from media.media import *

from machine import FPIOA, UART


# ============================================================
# 图像尺寸
# ============================================================

WIDTH = 640
HEIGHT = 480


# ============================================================
# 要识别的颜色
# ============================================================

TARGET_COLOR = "black"


# ============================================================
# LAB 阈值
# ============================================================

COLOR_THRESHOLDS = {

    "red": (
        0, 66,
        7, 127,
        3, 127
    ),

    "green": (
        42, 100,
        -128, -17,
        6, 66
    ),

    "blue": (
        43, 99,
        -43, -4,
        -56, -7
    ),

    "black": (
        0, 35,
        -128, 127,
        -128, 127
    )
}


PIXELS_THRESHOLD = 100
AREA_THRESHOLD = 500


sensor = None


# ============================================================
# UART 初始化
#
# K230 IO9 = UART1 TX
# K230 IO10 = UART1 RX
#
# 实际测试：
# K230 TX -> Arduino Nano D12
# K230 GND -> Arduino Nano GND
# ============================================================

fpioa = FPIOA()

fpioa.set_function(
    9,
    FPIOA.UART1_TXD
)

fpioa.set_function(
    10,
    FPIOA.UART1_RXD
)


uart = UART(
    UART.UART1,
    baudrate=57600,
    bits=UART.EIGHTBITS,
    parity=UART.PARITY_NONE,
    stop=UART.STOPBITS_ONE
)


print("UART 初始化完成")


# ============================================================
# 串口发送间隔
#
# 50ms = 每秒约20次
# 对巡线已经足够，而且 Nano 更容易稳定接收
# ============================================================

SEND_INTERVAL = 50

last_send_time = 0


# ============================================================
# 找最大的色块
# ============================================================

def get_largest_blob(blobs):

    if not blobs:
        return None

    largest = None
    largest_area = 0

    for blob in blobs:

        w = blob[2]
        h = blob[3]

        area = w * h

        if area > largest_area:

            largest_area = area
            largest = blob

    return largest


# ============================================================
# 发送线路中心给 Arduino
# ============================================================

def send_cx(cx):

    global last_send_time

    now = time.ticks_ms()

    if time.ticks_diff(
        now,
        last_send_time
    ) >= SEND_INTERVAL:

        message = "CX:%d\n" % cx

        uart.write(
            message.encode()
        )

        last_send_time = now


# ============================================================
# 发送丢线信息
# ============================================================

def send_no_line():

    global last_send_time

    now = time.ticks_ms()

    if time.ticks_diff(
        now,
        last_send_time
    ) >= SEND_INTERVAL:

        uart.write(
            b"NO_LINE\n"
        )

        last_send_time = now


# ============================================================
# 主程序
# ============================================================

try:

    # ========================================================
    # 初始化摄像头
    # 保持你已经测试成功的方式
    # ========================================================

    sensor = Sensor()

    sensor.reset()

    sensor.set_framesize(
        width=WIDTH,
        height=HEIGHT
    )

    sensor.set_pixformat(
        Sensor.RGB565
    )


    # ========================================================
    # 初始化屏幕
    # 保持原来可以正常运行的方式
    # ========================================================

    Display.init(
        Display.ST7701,
        to_ide=True
    )

    MediaManager.init()

    sensor.run()


    print("============================")
    print("K230 颜色巡线 + UART")
    print("目标颜色:", TARGET_COLOR)
    print("UART 波特率: 57600")
    print("============================")


    time.sleep_ms(1000)


    # ========================================================
    # 主循环
    # ========================================================

    while True:

        time.sleep_ms(10)


        # ====================================================
        # 获取画面
        # ====================================================

        img = sensor.snapshot()


        # ====================================================
        # 查找目标颜色
        # ====================================================

        blobs = img.find_blobs(

            [COLOR_THRESHOLDS[TARGET_COLOR]],

            pixels_threshold=PIXELS_THRESHOLD,

            area_threshold=AREA_THRESHOLD,

            merge=True
        )


        # ====================================================
        # 找最大的色块
        # ====================================================

        blob = get_largest_blob(blobs)


        # ====================================================
        # 找到黑线
        # ====================================================

        if blob is not None:

            x = blob[0]
            y = blob[1]

            w = blob[2]
            h = blob[3]

            cx = blob[5]
            cy = blob[6]


            # ================================================
            # 画识别框
            # ================================================

            img.draw_rectangle(

                (x, y, w, h),

                color=(255, 0, 0),

                thickness=3
            )


            # ================================================
            # 画黑线中心
            # ================================================

            img.draw_cross(

                cx,
                cy,

                color=(0, 255, 0),

                thickness=3
            )


            # ================================================
            # 画摄像头中心线
            # ================================================

            img.draw_line(

                WIDTH // 2,
                0,

                WIDTH // 2,
                HEIGHT,

                color=(0, 0, 255),

                thickness=2
            )


            # ================================================
            # 计算偏差
            # ================================================

            error = cx - WIDTH // 2


            # ================================================
            # IDE 输出
            # ================================================

            print(

                "识别成功",

                "x =", x,
                "y =", y,

                "w =", w,
                "h =", h,

                "cx =", cx,
                "cy =", cy,

                "error =", error
            )


            # ================================================
            # 发送给 Arduino
            #
            # 例如：
            #
            # CX:318
            #
            # ================================================

            send_cx(cx)


        # ====================================================
        # 没找到黑线
        # ====================================================

        else:

            print(
                "未识别到",
                TARGET_COLOR
            )

            send_no_line()


        # ====================================================
        # 显示图像
        # ====================================================

        Display.show_image(img)


        # ====================================================
        # 内存回收
        # ====================================================

        gc.collect()


# ============================================================
# 停止运行
# ============================================================

except KeyboardInterrupt:

    print("程序停止")


# ============================================================
# 其他错误
# ============================================================

except BaseException as e:

    print("============================")
    print("程序发生错误")
    print(e)
    print("============================")


# ============================================================
# 释放资源
# ============================================================

finally:

    if isinstance(sensor, Sensor):

        sensor.stop()


    Display.deinit()

    MediaManager.deinit()


    print("程序结束")
